//go:build packhistory

package bundled

import (
	"os"
	"path/filepath"
	"slices"
	"strings"
	"testing"
)

// TestWritePackHistory is the generator dev/packhistory runs, kept in this package so
// it fingerprints each skill with [digest] itself and cannot drift from it. It is
// built only with the packhistory tag, so an ordinary test run neither compiles nor
// skips it. FLYNN_PACK_TREES names a directory with one subdirectory per historical
// pack tree, each holding a "skills" directory laid out like the embedded one, and
// FLYNN_PACK_HISTORY_OUT the file to write.
func TestWritePackHistory(t *testing.T) {
	trees, out := os.Getenv("FLYNN_PACK_TREES"), os.Getenv("FLYNN_PACK_HISTORY_OUT")
	if trees == "" || out == "" {
		t.Skip("generator: run dev/packhistory")
	}
	dirs, err := filepath.Glob(filepath.Join(trees, "*"))
	if err != nil || len(dirs) == 0 {
		t.Fatalf("no trees under %s (err %v)", trees, err)
	}
	seen := map[string]bool{}
	var lines []string
	loaded := 0
	for _, dir := range dirs {
		skills, err := skillsFrom(os.DirFS(dir), Root)
		if err != nil {
			// A tree the loader rejects predates the first release that seeded the
			// pack, so no install holds a copy of it.
			t.Logf("skipping %s: %v", filepath.Base(dir), err)
			continue
		}
		loaded++
		for _, sk := range skills {
			line := sk.Slug + " " + digest(sk)
			if !seen[line] {
				seen[line] = true
				lines = append(lines, line)
			}
		}
	}
	if loaded == 0 {
		t.Fatal("no tree loaded")
	}
	slices.Sort(lines)
	header := "# Every version of each bundled skill the pack has carried: slug, then the\n" +
		"# digest of that version. Generated by dev/packhistory; do not edit.\n"
	if err := os.WriteFile(out, []byte(header+strings.Join(lines, "\n")+"\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	t.Logf("wrote %d digests from %d of %d trees", len(lines), loaded, len(dirs))
}
